"""Compile ID-first UTF-8 TOML overrides into a C macro include."""

from collections.abc import Sequence
import os
from pathlib import Path
import tomllib
from typing import Annotated

import typer

from rotkit.cheaders import extract_defines, extract_enum
from rotkit.paths import BUILD, ROOT
from rotkit.text_encoding import unicode_to_game

PATCH_ROOT = ROOT / "hacks/patches"
PATCH_CONFIG = ROOT / "hacks/patches.cfg"
PATTERN = "*.text-override.toml"
OUTPUT = BUILD / "hack_include/text_overrides.inc"
LANGUAGES = {
    "en": "LANGUAGE_EN",
    "fr": "LANGUAGE_FR",
    "de": "LANGUAGE_DE",
    "it": "LANGUAGE_IT",
    "es": "LANGUAGE_ES",
}


def discover_sources(
    source: Path | None = None, patches: str | None = None
) -> list[Path]:
    """Find override files in selected patches or an explicit source directory."""
    if source is not None:
        if patches is not None:
            raise ValueError("use either --source or --patches, not both")
        if not source.is_dir():
            raise ValueError(f"{source}: override directory does not exist")
        return sorted(path for path in source.glob(PATTERN) if path.is_file())

    tokens = (os.environ.get("HACKS", "@cfg") if patches is None else patches).split()
    selected = set(tokens) - {"@cfg"}
    if "@cfg" in tokens:
        for line in PATCH_CONFIG.read_text().splitlines():
            selected.update(line.partition("#")[0].split())
    available = {path.name for path in PATCH_ROOT.iterdir() if path.is_dir()}
    unknown = selected - available
    if unknown:
        raise ValueError(f"unknown patches: {', '.join(sorted(unknown))}")
    paths = sorted(
        path
        for patch in selected
        for path in (PATCH_ROOT / patch).glob(PATTERN)
        if path.is_file()
    )
    if paths and "text_overrides" not in selected:
        raise ValueError(
            "text overrides require the text_overrides patch "
            f"(files: {', '.join(str(path) for path in paths)})"
        )
    return paths


def load_overrides(paths: Sequence[Path]) -> dict[tuple[str, str], bytes]:
    """Validate declarations and return encoded strings keyed by ID and language."""
    ids = extract_enum("carved/include/text_ids.h", "TextId")
    capacity = extract_defines("include/text.h", {"TEXT_STRING_BUFFER_SIZE"})[
        "TEXT_STRING_BUFFER_SIZE"
    ]
    result = {}
    origins = {}
    for path in sorted(paths):
        try:
            tables = tomllib.loads(path.read_text(encoding="utf-8"))
        except (tomllib.TOMLDecodeError, UnicodeDecodeError) as error:
            raise ValueError(f"{path}: {error}") from error
        for text_id, translations in tables.items():
            context = f"{path}: {text_id}"
            if text_id not in ids:
                raise ValueError(f"{context}: unknown text ID")
            if not isinstance(translations, dict):
                raise ValueError(f"{context}: expected a table of language strings")
            for language, text in translations.items():
                context = f"{path}: {text_id}.{language}"
                if language not in LANGUAGES:
                    raise ValueError(f"{context}: unknown language")
                if not isinstance(text, str):
                    raise ValueError(f"{context}: expected a string")
                key = (text_id, language)
                if key in result:
                    raise ValueError(
                        f"{context}: duplicate override (first declared in {origins[key]})"
                    )
                try:
                    value = unicode_to_game(text)
                except ValueError as error:
                    raise ValueError(f"{context}: {error}") from error
                if len(value) + 1 > capacity:
                    raise ValueError(
                        f"{context}: encoded string needs {len(value) + 1} bytes "
                        f"including the terminator (maximum {capacity})"
                    )
                result[key] = value
                origins[key] = path
    return result


def render_include(overrides: dict[tuple[str, str], bytes]) -> str:
    lines = ["// Generated by rotkit hack text-overrides. Do not edit."]
    for (text_id, language), value in overrides.items():
        # Fixed-width octal escapes cannot absorb a following digit or form trigraphs.
        literal = '"' + "".join(f"\\{byte:03o}" for byte in value) + '"'
        lines.append(f"TEXT_OVERRIDE({LANGUAGES[language]}, {text_id}, {literal})")
    return "\n".join(lines) + "\n"


def run(
    source: Annotated[
        Path | None,
        typer.Option(exists=True, file_okay=False, help="use only this override directory"),
    ] = None,
    out: Path = OUTPUT,
    patches: Annotated[
        str | None,
        typer.Option(help="patch selection, e.g. '@cfg balance' (default: HACKS or @cfg)"),
    ] = None,
) -> None:
    """Compile selected *.text-override.toml files into an encoded C include."""
    overrides = load_overrides(discover_sources(source, patches))
    content = render_include(overrides)
    out.parent.mkdir(parents=True, exist_ok=True)
    if not out.exists() or out.read_text(encoding="ascii") != content:
        out.write_text(content, encoding="ascii")
    print(f"text overrides: {len(overrides)} strings -> {out}")
