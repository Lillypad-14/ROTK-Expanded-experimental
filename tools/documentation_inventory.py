"""Regenerate the community source inventory without a ROM or build artifacts."""

from pathlib import Path

from rotkit.decomp import _parse_file
from rotkit.paths import ROOT
from rotkit.stores import func_symbols, read_split


def link(path: str) -> str:
    if path.startswith("build/"):
        return f"`{path}` (generated locally)"
    return f"[{path}](../{path})"


def main() -> None:
    root = Path(ROOT)
    split = read_split()
    symbols = func_symbols()
    files = sorted((root / "src/c").rglob("*.c"))
    definitions = {
        path.relative_to(root).as_posix(): [
            name for name, _, _ in _parse_file(str(path))
        ]
        for path in files
    }
    defined = {name for names in definitions.values() for name in names}
    missing = [symbol for symbol in symbols if symbol.name not in defined]
    lines = [
        "# Source inventory",
        "",
        "Generated by `uv run python tools/documentation_inventory.py`. Do not edit this file by hand.",
        "This is a source inventory, not a fresh byte-match or runtime test result.",
        "",
        f"- {len(defined)} distinct non-inline C function names in {len(files)} source files.",
        f"- {sum(path.startswith('src/c/') for path in split)} C regions in the reconstruction manifest.",
        f"- {len(symbols)} mapped original-game function symbols, including {len(missing)} without a C definition.",
        f"- {sum(not path.startswith('src/c/') for path in split)} other manifest regions, including carved data and generated assets.",
        "",
        "The mapped symbol list is incomplete. These counts cannot establish a full-game decompilation percentage.",
        "C presence and manifest membership identify candidates for verification. Run `make verify` to establish byte identity.",
        "Run `make coverage` for compiled byte sizes and the remaining base-ROM spans after building.",
        "Hack implementations in `hacks/` are new behavior and are counted separately from original-game C.",
        "",
        "## Original-game C by source file",
        "",
        "Functions are grouped by translation unit. Names and behavior comments live in the linked C definitions.",
        "Manifest addresses are starts of source regions, not addresses of every function within them.",
        "",
        "| Source | Manifest start | C functions |",
        "| --- | --- | --- |",
    ]
    for path, names in definitions.items():
        address = f"`0x{split[path]:08x}`" if path in split else "Not in manifest"
        lines.append(
            f"| {link(path)} | {address} | {', '.join(f'`{name}`' for name in names)} |"
        )
    lines += [
        "",
        "## Mapped functions without C",
        "",
        "Mapped names may be provisional. A symbol or header prototype alone is not a decompilation.",
        "",
        "| Address | Mode | Function |",
        "| --- | --- | --- |",
    ]
    lines += [f"| `0x{s.addr:08x}` | {s.mode} | `{s.name}` |" for s in missing]
    lines += [
        "",
        "## Reconstructed data and asset regions",
        "",
        "These regions participate in ROM reconstruction but are excluded from the C counts.",
        "",
        "| Manifest start | Source |",
        "| --- | --- |",
    ]
    lines += [
        f"| `0x{address:08x}` | {link(path)} |"
        for path, address in sorted(split.items(), key=lambda row: row[1])
        if not path.startswith("src/c/")
    ]
    enabled = {
        line.split("#", 1)[0].strip()
        for line in (root / "hacks/patches.cfg").read_text().splitlines()
    } - {""}
    lines += [
        "",
        "## Mod patch inventory",
        "",
        "Selection comes from `hacks/patches.cfg`. A directory's presence does not mean it is enabled or independently selectable.",
        "",
        "| Patch | Default selection | Source |",
        "| --- | --- | --- |",
    ]
    for path in sorted((root / "hacks/patches").iterdir()):
        if path.is_dir():
            rel = path.relative_to(root).as_posix()
            lines.append(
                f"| `{path.name}` | {'Enabled' if path.name in enabled else 'Not selected'} | {link(rel)} |"
            )
    lines += [
        "",
        "## Mod implementation files",
        "",
        "These implement new behavior and hooks rather than byte-matched original-game C.",
        "",
        "| Component | C sources |",
        "| --- | --- |",
    ]
    for path in sorted((root / "hacks/patches").iterdir()):
        if path.is_dir():
            sources = sorted(path.glob("*.c"))
            lines.append(
                f"| `{path.name}` | {', '.join(link(source.relative_to(root).as_posix()) for source in sources) or 'Assembly/data only'} |"
            )
    lines += [
        "",
        "## Shared mod APIs",
        "",
        "See [shared ability support](ability-support.md) for contracts and [the change overview](expanded-changes.md) for subsystem context.",
        "",
    ]
    lines += [
        f"- {link(path.relative_to(root).as_posix())}"
        for path in sorted((root / "hacks/lib").glob("*.h"))
    ]
    lines += [
        "",
        "## Authoring and validation tools",
        "",
        "Test modules describe automated coverage, not full hardware or emulator certification.",
        "",
    ]
    lines += [
        f"- {link(path.relative_to(root).as_posix())}"
        for path in sorted((root / "hacks/tools").glob("*.py"))
    ]
    (root / "docs/source-inventory.md").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )


if __name__ == "__main__":
    main()
