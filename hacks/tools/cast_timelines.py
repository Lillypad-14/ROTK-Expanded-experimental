"""Compile cast timelines and an SVG timing chart from the shared effect catalog."""

from html import escape
import json
from pathlib import Path

from skill_fx import ROOT, fields, key, number, require


def generate(manifest: Path, effects: Path, output: Path, preview: Path) -> None:
    document = json.loads(manifest.read_text())
    fields(document, {"version", "timelines"}, "timeline manifest")
    require(document["version"] == 1, "unsupported timeline version")
    catalog = {
        effect["key"]: effect["id"]
        for effect in json.loads(effects.read_text())["effects"]
    }
    timelines = document["timelines"]
    number(len(timelines), 1, 16, "timeline count")
    code, identifiers, names, definitions, charts, used = (
        [],
        [],
        ['"Native"'],
        [],
        [],
        set(),
    )
    anchors = {"owner": 0, "target": 1, "position": 2}
    for index, timeline in enumerate(timelines):
        fields(
            timeline,
            {"key", "id", "name", "releaseTick", "recoveryTicks", "events"},
            "timeline",
        )
        name = key(timeline["key"])
        require(name not in used, "duplicate timeline key")
        used.add(name)
        require(
            number(timeline["id"], 0, 15, "timeline ID") == index,
            "timeline IDs must be consecutive",
        )
        label = timeline["name"]
        require(
            isinstance(label, str)
            and label.isascii()
            and label.isprintable()
            and 1 <= len(label) <= 16,
            "invalid timeline name",
        )
        release = number(timeline["releaseTick"], 0, 3600, "release tick")
        recovery = number(
            timeline["recoveryTicks"], 0, 3600 - release, "recovery ticks"
        )
        entries = []
        previous = 0
        number(len(timeline["events"]), 0, 16, "event count")
        for event in timeline["events"]:
            fields(event, {"tick", "effect", "anchor"}, "timeline event")
            tick = number(event["tick"], previous, release + recovery, "event tick")
            require(event["effect"] in catalog, "unknown timeline effect")
            require(event["anchor"] in anchors, "unknown timeline anchor")
            previous = tick
            entries.append(
                f"{{{tick},{catalog[event['effect']]},{anchors[event['anchor']]}}}"
            )
        pointer = "NULL"
        if entries:
            pointer = "CastTimelineEvents_" + name
            code.append(
                f"static const HackLibTimelineEvent {pointer}[] = {{"
                + ",".join(entries)
                + "};"
            )
        definitions.append(f"{{{pointer},{release},{recovery},{len(entries)}}}")
        identifiers.append(f"    HACKLIB_TIMELINE_{name.upper()} = {index},")
        names.append(json.dumps(label))
        scale = 500 / max(release + recovery, 1)
        markers = "".join(
            f'<circle cx="{70 + event["tick"] * scale}" cy="55" r="4" fill="#f9c85c"><title>{escape(event["effect"])}</title></circle>'
            for event in timeline["events"]
        )
        charts.append(
            f'<h2>{escape(label)}</h2><svg viewBox="0 0 640 100" role="img" aria-label="{escape(label)} cast timing"><rect x="70" y="30" width="{release * scale}" height="40" fill="#477ca8"/><rect x="{70 + release * scale}" y="30" width="{recovery * scale}" height="40" fill="#755487"/>{markers}<text x="70" y="22">Windup: {release} ticks</text><text x="340" y="22">Recovery: {recovery} ticks</text><path d="M {70 + release * scale} 25 v 50" stroke="#fff" stroke-width="2"/><text x="70" y="90">Release at {release / 30:.2f}s; total {(release + recovery) / 30:.2f}s</text></svg>'
        )
    code += [
        "const HackLibCastTimeline HackLibCastTimelines[] = {"
        + ",".join(definitions)
        + "};",
        "const char *const HackLibCastTimelineNames[] = {" + ",".join(names) + "};",
    ]
    output.mkdir(parents=True, exist_ok=True)
    (output / "cast_timeline_data.inc").write_text(
        "// Generated by hacks/tools/cast_timelines.py.\n" + "\n".join(code) + "\n",
        newline="\n",
    )
    (output / "cast_timeline_ids.h").write_text(
        "#pragma once\nenum HackLibTimelineId {\n"
        + "\n".join(identifiers)
        + f"\n    HACKLIB_CAST_TIMELINE_COUNT = {len(timelines)}\n}};\n",
        newline="\n",
    )
    preview.mkdir(parents=True, exist_ok=True)
    (preview / "timelines.html").write_text(
        '<!doctype html><meta charset="utf-8"><title>Cast timelines</title><style>body{background:#182228;color:#eee;font:16px system-ui;margin:2rem}svg{max-width:800px;display:block;background:#26353e}text{fill:#eee;font:14px system-ui}</style><h1>Cast timelines</h1><p>30 game ticks per second. Blue: windup; purple: cast recovery; gold: visual cues. Hover over a cue for its effect name.</p>'
        + "".join(charts),
        newline="\n",
    )
    print(f"Cast timelines: {len(timelines)} validated")


if __name__ == "__main__":
    generate(
        ROOT / "hacks/content/cast_timelines.json",
        ROOT / "hacks/content/skill_fx.json",
        ROOT / "build/hack_include",
        ROOT / "build/skill_fx_preview",
    )
