"""Combine the stock shockwave halves into one effect actor.

The build writes build/generated/fx_shockwave.c from the base ROM, so no stock art is committed.
Run by hand: uv run python hacks/tools/ground_shockwave.py [output.c]
"""

from dataclasses import replace
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))

from rotkit.compression import lz77
from rotkit.spritegfx import SPRITE_FRAME_LZ77, decode_frame_tiles, parse_frame_set


def combine(rom: bytes) -> tuple[bytes, bytes]:
    halves = []
    for shape in (21, 20):
        tiles, frames = struct.unpack_from("<II", rom, 0x287B7C + shape * 20)
        halves.append((tiles - 0x08000000, parse_frame_set(rom, frames)))
    count = halves[0][1].frame_count
    assert count == halves[1][1].frame_count == 17
    records, offsets = [], []
    tiles = bytearray()
    largest = 0
    for index in range(count):
        raw = bytearray()
        objects = []
        for address, frame_set in halves:
            frame = frame_set.frames[index]
            objects.extend(
                replace(obj, tile_offset=obj.tile_offset + len(raw) // 32)
                for obj in frame.oam
            )
            raw.extend(decode_frame_tiles(rom[address:], frame))
        assert len(objects) <= 31 and len(raw) <= 2304
        largest = max(largest, len(raw))
        record = struct.pack(
            "<BBBBHH", SPRITE_FRAME_LZ77 | len(objects), 0, 64, 32, len(tiles), len(raw)
        )
        record += b"".join(struct.pack("<I", obj.pack()) for obj in objects)
        records.append(record)
        compressed = lz77.encode(bytes(raw))
        tiles.extend(compressed + bytes(-len(compressed) % 4))
    assert len(tiles) <= 65535
    cursor = count * 2
    for record in records:
        offsets.append(cursor)
        cursor += len(record)
    frames = struct.pack("<BB4bHHBB", 64, 32, 0, 0, 0, 0, count, largest, 0, 0)
    frames += struct.pack(f"<{count}H", *offsets) + b"".join(records)
    return bytes(tiles), frames


def array(name: str, data: bytes) -> str:
    rows = [
        "    " + " ".join(f"0x{value:02x}," for value in data[i : i + 16])
        for i in range(0, len(data), 16)
    ]
    return (
        f"static const u8 {name}[] __attribute__((aligned(4))) = {{\n"
        + "\n".join(rows)
        + "\n};\n"
    )


def source(rom: bytes) -> str:
    tiles, frames = combine(rom)
    return (
        "// Generated by hacks/tools/ground_shockwave.py. Do not edit.\n\n"
        '#include "lib/fx_shockwave.h"\n\n'
        + array("ShockwaveTiles", tiles)
        + "\n"
        + array("ShockwaveFrames", frames)
        + "\n"
        + "const SpriteAnimation HackLibFxGroundShockwave = {\n"
        "    .tiles = ShockwaveTiles,\n"
        "    .frames = (const SpriteFrameSetHeader *)ShockwaveFrames,\n"
        "    .palette = NULL,\n"
        "    .frameDuration = 1,\n"
        "};\n"
    )


if __name__ == "__main__":
    output = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "build/generated/fx_shockwave.c"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(source((ROOT / "rotk.gba").read_bytes()), newline="\n")
